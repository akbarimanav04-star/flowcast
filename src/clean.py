"""M2 - Cleaning, wrangling & merge (PRD section 9, stages 1-6 + 8).

Order matters: validate -> de-duplicate -> outliers -> missing values ->
harmonise categories -> align & merge -> quality checks.
"""
from __future__ import annotations

import hashlib
import json

import numpy as np
import pandas as pd

from .ingest import load_raw
from .utils import CFG, CONGESTION_ORDER, get_logger, path

log = get_logger("clean")

WEATHER_MAP = {"clear": "Clear", "cloudy": "Cloudy", "overcast": "Cloudy",
               "rain": "Rain", "rainy": "Rain", "fog": "Fog", "foggy": "Fog"}
STATIC_COLS = ["road_name", "latitude", "longitude", "weather_station_id", "road_capacity"]
FILL_COLS = ["traffic_volume", "avg_speed", "occupancy", "travel_time", "signal_timing"]
SHARE_COLS = ["share_2W", "share_Car", "share_LCV", "share_HCV"]


class QualityLog:
    """Collects one entry per cleaning step -> rendered as reports/data_quality.md."""

    def __init__(self):
        self.entries: list[tuple[str, str, int | float | str]] = []

    def add(self, stage: str, issue: str, value) -> None:
        self.entries.append((stage, issue, value))
        log.info("%-22s %-48s %s", stage, issue, value)

    def to_markdown(self) -> str:
        lines = ["# FlowCast - Data Quality Report", "",
                 "Auto-generated by `src/clean.py`. Every defect found in the raw tables and how it was resolved.", "",
                 "| Stage | Issue / action | Count / value |", "|---|---|---|"]
        lines += [f"| {s} | {i} | {v} |" for s, i, v in self.entries]
        return "\n".join(lines) + "\n"


# ----------------------------------------------------------------------------- helpers
def _fill_short_gaps(s: pd.Series, limit: int) -> pd.Series:
    """Linear-interpolate only NaN runs of length <= limit; longer runs stay NaN."""
    isn = s.isna()
    run_id = (isn != isn.shift()).cumsum()
    run_len = isn.groupby(run_id).transform("sum")
    interp = s.interpolate(method="linear", limit_area="inside")
    return s.where(~(isn & (run_len <= limit)), interp)


def derive_congestion(volume: pd.Series, capacity: pd.Series) -> pd.Series:
    """Volume-to-capacity banding from the data dictionary (capacity/2 = 30-min capacity)."""
    b = CFG["congestion_bands"]
    vc = volume / (capacity / 2.0)
    out = pd.Series(np.select([vc < b["moderate"], vc < b["heavy"], vc < b["severe"]],
                              CONGESTION_ORDER[:3], default=CONGESTION_ORDER[3]), index=volume.index)
    return out.where(vc.notna())


# ----------------------------------------------------------------------------- traffic
def clean_traffic(t: pd.DataFrame, ql: QualityLog) -> pd.DataFrame:
    ql.add("1 validate", "traffic rows loaded", len(t))
    ql.add("1 validate", "rows with a range-rule violation (quarantined + repaired)", int((t.qc_reason != "").sum()))

    # 2. duplicates ------------------------------------------------------------------
    exact = int(t.duplicated(subset=[c for c in t.columns if c != "qc_reason"]).sum())
    t = t.assign(_nn=t.notna().sum(axis=1)).sort_values(["road_id", "timestamp", "_nn"], ascending=[True, True, False])
    key_dups = int(t.duplicated(["road_id", "timestamp"]).sum())
    t = t.drop_duplicates(["road_id", "timestamp"], keep="first").drop(columns="_nn")
    ql.add("2 duplicates", "exact duplicate rows", exact)
    ql.add("2 duplicates", "key-level (road_id+timestamp) duplicates removed", key_dups)

    # 3. outliers (rule-based) ---------------------------------------------------------
    v = CFG["validation"]
    neg = t.traffic_volume < v["min_volume"]
    # vehicle_count is the raw detector count and equals volume in this release (data dictionary),
    # so it is the best, exact repair for null / negative volume.
    recover = (t.traffic_volume.isna() | neg) & (t.vehicle_count >= 0)
    ql.add("3 outliers", "negative traffic_volume", int(neg.sum()))
    ql.add("3 outliers", "null/negative volume recovered exactly from vehicle_count", int(recover.sum()))
    t.loc[recover, "traffic_volume"] = t.loc[recover, "vehicle_count"]
    t.loc[t.traffic_volume < v["min_volume"], "traffic_volume"] = np.nan

    bad_speed = (t.avg_speed > v["max_speed_kmh"]) | (t.avg_speed <= 0)
    bad_occ = (t.occupancy > v["max_occupancy_pct"]) | (t.occupancy < 0)
    ql.add("3 outliers", f"avg_speed > {v['max_speed_kmh']} km/h -> set to NaN", int(bad_speed.sum()))
    ql.add("3 outliers", f"occupancy > {v['max_occupancy_pct']}% -> set to NaN", int(bad_occ.sum()))
    t.loc[bad_speed, "avg_speed"] = np.nan
    t.loc[bad_occ, "occupancy"] = np.nan

    # statistical outliers: IQR fence computed per road x hour (peaks are normal, so compare like with like)
    k = CFG["cleaning"]["iqr_k"]
    t["_hour"] = t.timestamp.dt.hour
    capped = 0
    for col in ["traffic_volume", "avg_speed", "occupancy"]:
        g = t.groupby(["road_id", "_hour"])[col]
        q1, q3 = g.transform(lambda s: s.quantile(.25)), g.transform(lambda s: s.quantile(.75))
        iqr = q3 - q1
        lo, hi = q1 - k * iqr, q3 + k * iqr
        mask = (t[col] < lo) | (t[col] > hi)
        capped += int(mask.sum())
        t[col] = t[col].clip(lower=lo, upper=hi)
    ql.add("3 outliers", f"IQR(k={k}) extremes per road x hour -> capped (winsorised)", capped)
    t = t.drop(columns="_hour")

    # 4a. expose absent windows: reindex every road to the full 30-min grid ----------------
    static = t.groupby("road_id")[STATIC_COLS].agg(lambda s: s.mode().iat[0])
    full_idx = pd.date_range(t.timestamp.min(), t.timestamp.max(), freq="30min")
    grid = pd.MultiIndex.from_product([static.index, full_idx], names=["road_id", "timestamp"])
    t = t.set_index(["road_id", "timestamp"]).reindex(grid).reset_index()
    absent = int(t.traffic_volume.isna().sum())
    t = t.drop(columns=STATIC_COLS).merge(static.reset_index(), on="road_id", how="left")
    ql.add("4 missing", "absent 30-min windows (sensor dropout) re-inserted as empty rows",
           int(t.date.isna().sum()))
    ql.add("4 missing", "rows with null volume after repairs (to impute)", absent)

    # 4b. impute -------------------------------------------------------------------------
    t["is_imputed"] = t.traffic_volume.isna().astype(int)
    t = t.sort_values(["road_id", "timestamp"]).reset_index(drop=True)
    t["weekday"] = t.timestamp.dt.dayofweek
    t["slot"] = t.timestamp.dt.hour * 2 + t.timestamp.dt.minute // 30
    limit = CFG["cleaning"]["short_gap_windows"]
    n_before = {c: int(t[c].isna().sum()) for c in FILL_COLS}
    for col in FILL_COLS:
        t[col] = t.groupby("road_id", group_keys=False)[col].apply(lambda s: _fill_short_gaps(s, limit))
    n_after_interp = {c: int(t[c].isna().sum()) for c in FILL_COLS}
    for col in FILL_COLS:   # long gaps: road x weekday x slot median
        med = t.groupby(["road_id", "weekday", "slot"])[col].transform("median")
        t[col] = t[col].fillna(med)
        t[col] = t[col].fillna(t.groupby(["road_id", "slot"])[col].transform("median"))
    ql.add("4 missing", f"short gaps (<= {limit} windows) filled by time interpolation",
           sum(n_before[c] - n_after_interp[c] for c in FILL_COLS))
    ql.add("4 missing", "long gaps filled with road x weekday x slot median",
           sum(n_after_interp[c] for c in FILL_COLS))
    t["accident_count"] = t["accident_count"].fillna(0).astype(int)   # absent window -> no reported incident
    t["traffic_volume"] = t["traffic_volume"].round().astype(int)
    t["signal_timing"] = t["signal_timing"].round().astype(int)

    # vehicle_type_dist (JSON string) -> 4 numeric share columns
    parsed = t["vehicle_type_dist"].map(lambda s: json.loads(s) if isinstance(s, str) else {})
    for key, col in zip(["2W", "Car", "LCV", "HCV"], SHARE_COLS):
        t[col] = parsed.map(lambda d, k=key: d.get(k, np.nan))
        t[col] = t[col].fillna(t.groupby("road_id")[col].transform("median"))
    ql.add("5 harmonise", "vehicle_type_dist JSON parsed into share_2W/Car/LCV/HCV", len(t))

    # 5. congestion label ------------------------------------------------------------------
    rule = derive_congestion(t.traffic_volume, t.road_capacity)
    blank = t.congestion_level.isna() | (t.is_imputed == 1)
    conflicts = int((t.congestion_level.notna() & ~blank & (t.congestion_level != rule)).sum())
    t["congestion_derived"] = blank.astype(int)
    t["congestion_level"] = t.congestion_level.where(~blank, rule)
    ql.add("5 harmonise", "blank/imputed congestion_level derived from volume/(capacity/2)", int(blank.sum()))
    ql.add("5 harmonise", "given labels that disagree with the V/C rule (kept as given)", conflicts)

    t = t.drop(columns=["vehicle_count", "vehicle_type_dist", "date", "time", "qc_reason", "weekday", "slot"])
    return t


# ----------------------------------------------------------------------------- weather / calendar
def clean_weather(w: pd.DataFrame, ql: QualityLog) -> pd.DataFrame:
    raw_labels = w.weather_condition.nunique()
    w = w.copy()
    w["weather_condition"] = w.weather_condition.str.strip().str.lower().map(WEATHER_MAP)
    unmapped = int(w.weather_condition.isna().sum())
    ql.add("5 harmonise", f"weather labels normalised ({raw_labels} raw spellings -> {w.weather_condition.nunique()})", len(w))
    ql.add("5 harmonise", "weather labels not in controlled vocabulary", unmapped)
    w["weather_condition"] = w.weather_condition.fillna("Clear")
    w = w.drop_duplicates(["station_id", "timestamp"]).sort_values(["station_id", "timestamp"])
    ql.add("4 missing", "weather temperature nulls", int(w.temperature.isna().sum()))
    ql.add("4 missing", "weather visibility nulls", int(w.visibility.isna().sum()))
    w["temperature"] = w.groupby("station_id")["temperature"].transform(
        lambda s: s.interpolate(limit=6, limit_area="inside"))
    w["temperature"] = w["temperature"].fillna(w.groupby("station_id")["temperature"].transform("median"))
    w["visibility"] = w["visibility"].fillna(w.groupby("weather_condition")["visibility"].transform("median"))
    return w[["station_id", "timestamp", "weather_condition", "temperature", "rainfall", "visibility"]]


def merge_all(t: pd.DataFrame, w: pd.DataFrame, c: pd.DataFrame, ql: QualityLog) -> pd.DataFrame:
    """Align hourly weather to 30-min windows (both halves of an hour share that hour) and join calendar."""
    n = len(t)
    t = t.copy()
    t["hour_ts"] = t.timestamp.dt.floor("h")
    w = w.rename(columns={"station_id": "weather_station_id", "timestamp": "hour_ts"})
    t = t.merge(w, on=["weather_station_id", "hour_ts"], how="left")
    # live / uploaded data may run past the last weather record: carry the last observation forward
    wcols = ["weather_condition", "temperature", "rainfall", "visibility"]
    t = t.sort_values(["road_id", "timestamp"])
    t[wcols] = t.groupby("road_id")[wcols].ffill()
    t["date"] = t.timestamp.dt.tz_localize(None).dt.normalize()
    t = t.merge(c.drop(columns=["qc_reason", "holiday_name", "event_name"]), on="date", how="left")
    for col in ["public_holiday", "event_flag", "roadwork_flag"]:
        t[col] = t[col].fillna(0).astype(int)
    assert len(t) == n, "merge changed the row count"
    ql.add("6 merge", "weather aligned hourly->30 min and calendar joined; rows preserved", len(t))
    t = t.drop(columns="hour_ts")
    return t.sort_values(["road_id", "timestamp"]).reset_index(drop=True)


def quality_checks(df: pd.DataFrame, ql: QualityLog) -> None:
    """Stage 8: assertions that must hold before modelling."""
    model_cols = ["traffic_volume", "avg_speed", "occupancy", "travel_time", "congestion_level",
                  "weather_condition", "temperature", "rainfall", "visibility", "signal_timing"]
    nulls = int(df[model_cols].isna().sum().sum())
    assert nulls == 0, f"nulls remain in modelling columns: {df[model_cols].isna().sum().to_dict()}"
    assert (df.traffic_volume >= 0).all() and (df.avg_speed.between(0, CFG["validation"]["max_speed_kmh"])).all()
    assert df.occupancy.between(0, 100).all()
    assert not df.duplicated(["road_id", "timestamp"]).any()
    ql.add("8 checks", "nulls in modelling columns", nulls)
    ql.add("8 checks", "final rows (25 roads x full 30-min grid)", len(df))
    ql.add("8 checks", "rows flagged is_imputed (volume estimated)", int(df.is_imputed.sum()))


def run(raw_dir: str | None = None, traffic_df: pd.DataFrame | None = None, save: bool = True) -> pd.DataFrame:
    """Raw CSVs -> one clean merged table (segment x 30-min window)."""
    ql = QualityLog()
    traffic, weather, calendar = load_raw(raw_dir, traffic_df)
    t = clean_traffic(traffic, ql)
    w = clean_weather(weather, ql)
    df = merge_all(t, w, calendar, ql)
    quality_checks(df, ql)
    if save:
        df.to_parquet(path(CFG["paths"]["processed"], "flowcast_clean.parquet"), index=False)
        version = hashlib.sha1(pd.util.hash_pandas_object(df, index=False).values.tobytes()).hexdigest()[:10]
        path(CFG["paths"]["processed"], "VERSION.txt").write_text(f"dataset_version: {version}\nrows: {len(df)}\n")
        path(CFG["paths"]["reports"], "data_quality.md").write_text(ql.to_markdown(), encoding="utf-8")
        log.info("saved processed dataset (version %s)", version)
    return df


if __name__ == "__main__":
    run()
